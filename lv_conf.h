/**
 * ============================================================================
 *  lv_conf.h —— LVGL 8.4.0 配置（ESP32-S3 + ST7789 240x320 电风扇 UI 专用）
 * ----------------------------------------------------------------------------
 *  为什么要有这个文件：
 *    Arduino 的 lvgl 库是 include "../../lv_conf.h" 找配置的，而
 *    Arduino/libraries/lv_conf.h 里那份是 v9 的模板（v9 已删掉
 *    LV_COLOR_16_SWAP 等宏），拿它配 8.4 会出现「配置看似没生效」的问题。
 *    lv_conf_internal.h 里有 __has_include("lv_conf.h")，只要 sketch 目录
 *    存在本文件，就会优先用这一份，且对 sketch 下所有 .c/.cpp 一致生效。
 *
 *  只写要覆盖的项，其余全部走 lv_conf_internal.h 的默认值，减少出错面。
 * ============================================================================
 */
#ifndef LV_CONF_H
#define LV_CONF_H

/* 给 fan_esp32s3.ino 做编译期自检，确认这份配置真的被用上了 */
#define FAN_LV_CONF_V84 1

#include <stdint.h>

/* ---------------------------------------------------------------------------
 * 颜色
 *   LV_COLOR_16_SWAP=0：lv_color_t 保持 MCU 本机字节序，
 *   flush 里交给 Adafruit 的 writePixels()，它在 ESP32 上会调
 *   SPI::writePixels() 做字节交换，正好是 ST7789 要的 MSB-first。
 *   别改成 1，否则颜色会变成花花绿绿的噪点。
 * ------------------------------------------------------------------------- */
#define LV_COLOR_DEPTH 16
#define LV_COLOR_16_SWAP 0

/* ---------------------------------------------------------------------------
 * 内存：LVGL 自己的堆（对象、样式、文本缓存都从这里出）
 *   这个界面约 40 个对象，48KB 实测余量充足；ESP32-S3 有 512KB SRAM。
 * ------------------------------------------------------------------------- */
#define LV_MEM_CUSTOM 0
#define LV_MEM_SIZE (48U * 1024U)

/* ---------------------------------------------------------------------------
 * 刷新周期 / 输入设备（本 UI 无触摸，输入部分不启用）
 * ------------------------------------------------------------------------- */
#define LV_DISP_DEF_REFR_PERIOD 30
#define LV_INDEV_DEF_READ_PERIOD 30

/* ---------------------------------------------------------------------------
 * 心跳：由 loop() 里的 lv_tick_inc() 提供，不依赖 millis 钩子
 * ------------------------------------------------------------------------- */
#define LV_TICK_CUSTOM 0

/* ---------------------------------------------------------------------------
 * 日志与断言：发布版关掉，省 flash、也省每次 malloc 的检查开销
 *   调试时把 LV_USE_ASSERT_NULL / MALLOC 打开，能立刻定位空指针
 * ------------------------------------------------------------------------- */
#define LV_USE_LOG 0
#define LV_USE_ASSERT_NULL 0
#define LV_USE_ASSERT_MALLOC 0
#define LV_USE_ASSERT_STYLE 0
#define LV_USE_ASSERT_MEM_INTEGRITY 0
#define LV_USE_ASSERT_OBJ 0

/* ---------------------------------------------------------------------------
 * 字体：界面全部中文走 font_cn.c；Montserrat 14 是 LVGL 的默认字体，
 * 内部（比如默认样式）会引用它，必须留一个。
 * ------------------------------------------------------------------------- */
#define LV_FONT_MONTSERRAT_14 1
#define LV_FONT_DEFAULT &lv_font_montserrat_14

#endif /* LV_CONF_H */
